def main():
    wb = Workbook()
    ws = wb.active
    ws.title = "产品信息"

    # 第 1 行：标题行（只填 A1，故意模仿真实表的合并标题）
    ws.cell(row=1, column=1, value="产品信息表（示例·假数据·不含任何公司信息）")

    # 第 2 行：真正的列名
    for i in range(len(COLUMNS)):
        ws.cell(row=2, column=i + 1, value=COLUMNS[i])

    # 第 3 行起：每个产品一行
    row_no = 3
    for item in PRODUCTS:
        for i in range(len(COLUMNS)):
            name = COLUMNS[i]
            ws.cell(row=row_no, column=i + 1, value=item.get(name))   # 没这个键 → 空单元格
        row_no = row_no + 1

    wb.save(OUT_PATH)

    print("已生成：" + OUT_PATH)
    print("  表结构：第 1 行标题 / 第 2 行列名 / 第 3 行起是数据")
    print("  产品数：" + str(len(PRODUCTS)))


if __name__ == "__main__":
    main()
